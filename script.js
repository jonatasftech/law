const languageMeta = {
  pt: { htmlLang: "pt-BR", titleWord: "Advocacia" },
  en: { htmlLang: "en", titleWord: "Legal Practice" },
  es: { htmlLang: "es", titleWord: "Abogacía" },
};

const header = document.querySelector("[data-header]");
const nav = document.querySelector("[data-nav]");
const navToggle = document.querySelector("[data-nav-toggle]");
const languageButtons = document.querySelectorAll("[data-lang]");

function textFor(key, language) {
  return translations[language]?.[key] || translations.pt[key] || "";
}

function applyProfile(language) {
  document.title = `${profile.name} | ${languageMeta[language].titleWord}`;

  document.querySelectorAll("[data-profile]").forEach((node) => {
    const key = node.dataset.profile;
    const value = profile[key];
    if (typeof value === "object" && value !== null) {
      node.textContent = value[language] || value.pt;
    } else if (value) {
      node.textContent = value;
    }
  });

  const contacts = {
    whatsapp: {
      href: `https://wa.me/${profile.whatsapp}`,
      label: profile.whatsappLabel,
    },
    email: {
      href: `mailto:${profile.email}`,
      label: profile.email,
    },
    linkedin: {
      href: profile.linkedin,
      label: profile.linkedinLabel,
    },
    instagram: {
      href: profile.instagram,
      label: profile.instagramLabel,
    },
  };

  Object.entries(contacts).forEach(([key, value]) => {
    const link = document.querySelector(`[data-contact="${key}"]`);
    const label = document.querySelector(`[data-contact-label="${key}"]`);
    if (link) link.href = value.href;
    if (label) label.textContent = value.label;
  });
}

function applyLanguage(language) {
  const selectedLanguage = translations[language] ? language : "pt";
  document.documentElement.lang = languageMeta[selectedLanguage].htmlLang;

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = textFor(node.dataset.i18n, selectedLanguage);
  });

  document.querySelectorAll("[data-i18n-attr]").forEach((node) => {
    node.dataset.i18nAttr.split(";").forEach((entry) => {
      const [attribute, key] = entry.split(":");
      if (attribute && key) node.setAttribute(attribute, textFor(key, selectedLanguage));
    });
  });

  languageButtons.forEach((button) => {
    const isSelected = button.dataset.lang === selectedLanguage;
    button.classList.toggle("is-active", isSelected);
    button.setAttribute("aria-pressed", String(isSelected));
  });

  localStorage.setItem("site-language", selectedLanguage);
  applyProfile(selectedLanguage);
}

function syncHeader() {
  header?.classList.toggle("is-scrolled", window.scrollY > 24);
}

function closeMenu() {
  nav?.classList.remove("is-open");
  header?.classList.remove("nav-active");
  document.body.classList.remove("nav-open");
  navToggle?.setAttribute("aria-expanded", "false");
}

const initialLanguage = localStorage.getItem("site-language") || "pt";
applyLanguage(initialLanguage);
syncHeader();

window.addEventListener("scroll", syncHeader, { passive: true });

languageButtons.forEach((button) => {
  button.addEventListener("click", () => applyLanguage(button.dataset.lang));
});

navToggle?.addEventListener("click", () => {
  const isOpen = nav.classList.toggle("is-open");
  header.classList.toggle("nav-active", isOpen);
  document.body.classList.toggle("nav-open", isOpen);
  navToggle.setAttribute("aria-expanded", String(isOpen));
});

nav?.addEventListener("click", (event) => {
  if (event.target.closest("a")) closeMenu();
});

if (window.lucide) {
  window.lucide.createIcons();
} else {
  window.addEventListener("load", () => window.lucide?.createIcons());
}
